-- ============================================================
-- 4. CUSTOMER BANK ACCOUNTS
-- One customer can own multiple accounts.
-- ============================================================

CREATE TABLE accounts (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          user_id BIGINT NOT NULL,

                          ledger_account_id BIGINT NOT NULL UNIQUE,

                          account_number VARCHAR(34) NOT NULL UNIQUE,

                          account_name VARCHAR(150) NOT NULL,

                          account_type VARCHAR(30) NOT NULL,

                          currency VARCHAR(3) NOT NULL,

                          balance DECIMAL(19,4) NOT NULL DEFAULT 0.0000,

                          status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                          created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_accounts_user
                              FOREIGN KEY (user_id) REFERENCES users(id),

                          CONSTRAINT fk_accounts_ledger
                              FOREIGN KEY (ledger_account_id) REFERENCES ledger_accounts(id),

                          CONSTRAINT ck_accounts_type
                              CHECK (
                                  account_type IN (
                                                   'SAVINGS',
                                                   'CURRENT',
                                                   'BUSINESS'
                                      )
                                  ),

                          CONSTRAINT ck_accounts_status
                              CHECK (
                                  status IN (
                                             'ACTIVE',
                                             'FROZEN',
                                             'CLOSED'
                                      )
                                  ),

                          CONSTRAINT ck_accounts_balance
                              CHECK (balance >= 0),

                          CONSTRAINT ck_accounts_currency
                              CHECK (currency = UPPER(currency))
);


CREATE INDEX idx_accounts_user_id ON accounts(user_id);

CREATE INDEX idx_accounts_status ON accounts(status);

CREATE INDEX idx_accounts_account_number
    ON accounts(account_number);


-- ============================================================
-- 5. BANK TRANSACTIONS
-- Deposits, withdrawals and transfers.
-- ============================================================

CREATE TABLE bank_transactions (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   reference VARCHAR(64) NOT NULL UNIQUE,

                                   transaction_type VARCHAR(30) NOT NULL,

                                   status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

                                   source_account_id BIGINT,

                                   destination_account_id BIGINT,

                                   amount DECIMAL(19,4) NOT NULL,

                                   currency VARCHAR(3) NOT NULL,

                                   description VARCHAR(500),

                                   created_by BIGINT,

                                   created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   completed_at TIMESTAMP WITH TIME ZONE,

                                   CONSTRAINT fk_transactions_source
                                       FOREIGN KEY (source_account_id) REFERENCES accounts(id),

                                   CONSTRAINT fk_transactions_destination
                                       FOREIGN KEY (destination_account_id) REFERENCES accounts(id),

                                   CONSTRAINT fk_transactions_user
                                       FOREIGN KEY (created_by) REFERENCES users(id),

                                   CONSTRAINT ck_transactions_type
                                       CHECK (
                                           transaction_type IN (
                                                                'DEPOSIT',
                                                                'WITHDRAWAL',
                                                                'TRANSFER'
                                               )
                                           ),

                                   CONSTRAINT ck_transactions_status
                                       CHECK (
                                           status IN (
                                                      'PENDING',
                                                      'COMPLETED',
                                                      'FAILED',
                                                      'REVERSED'
                                               )
                                           ),

                                   CONSTRAINT ck_transactions_amount
                                       CHECK (amount > 0),

                                   CONSTRAINT ck_transactions_currency
                                       CHECK (currency = UPPER(currency)),

                                   CONSTRAINT ck_transactions_accounts
                                       CHECK (
                                           source_account_id IS NULL
                                               OR destination_account_id IS NULL
                                               OR source_account_id <> destination_account_id
                                           ),

                                   CONSTRAINT ck_transactions_account_presence
                                       CHECK (
                                           (
                                               transaction_type = 'DEPOSIT'
                                                   AND source_account_id IS NULL
                                                   AND destination_account_id IS NOT NULL
                                               )
                                               OR
                                           (
                                               transaction_type = 'WITHDRAWAL'
                                                   AND source_account_id IS NOT NULL
                                                   AND destination_account_id IS NULL
                                               )
                                               OR
                                           (
                                               transaction_type = 'TRANSFER'
                                                   AND source_account_id IS NOT NULL
                                                   AND destination_account_id IS NOT NULL
                                               )
                                           )
);


CREATE INDEX idx_transactions_source
    ON bank_transactions(source_account_id);

CREATE INDEX idx_transactions_destination
    ON bank_transactions(destination_account_id);

CREATE INDEX idx_transactions_created_at
    ON bank_transactions(created_at);

CREATE INDEX idx_transactions_status
    ON bank_transactions(status);

CREATE INDEX idx_transactions_type
    ON bank_transactions(transaction_type);


-- ============================================================
-- 6. LEDGER ENTRIES
-- Financial accounting records.
-- Every completed transaction must have balanced entries.
-- ============================================================

CREATE TABLE ledger_entries (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                transaction_id BIGINT NOT NULL,

                                ledger_account_id BIGINT NOT NULL,

                                entry_side VARCHAR(10) NOT NULL,

                                amount DECIMAL(19,4) NOT NULL,

                                currency VARCHAR(3) NOT NULL,

                                description VARCHAR(500),

                                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_ledger_entries_transaction
                                    FOREIGN KEY (transaction_id)
                                        REFERENCES bank_transactions(id),

                                CONSTRAINT fk_ledger_entries_account
                                    FOREIGN KEY (ledger_account_id)
                                        REFERENCES ledger_accounts(id),

                                CONSTRAINT ck_ledger_entries_side
                                    CHECK (entry_side IN ('DEBIT', 'CREDIT')),

                                CONSTRAINT ck_ledger_entries_amount
                                    CHECK (amount > 0),

                                CONSTRAINT ck_ledger_entries_currency
                                    CHECK (currency = UPPER(currency))
);


CREATE INDEX idx_ledger_entries_transaction
    ON ledger_entries(transaction_id);

CREATE INDEX idx_ledger_entries_account
    ON ledger_entries(ledger_account_id);

CREATE INDEX idx_ledger_entries_created_at
    ON ledger_entries(created_at);


-- ============================================================
-- 7. REFRESH TOKENS
-- Store token hashes, never raw refresh tokens.
-- ============================================================

CREATE TABLE refresh_tokens (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                user_id BIGINT NOT NULL,

                                token_hash VARCHAR(255) NOT NULL UNIQUE,

                                expires_at TIMESTAMP WITH TIME ZONE NOT NULL,

                                revoked BOOLEAN NOT NULL DEFAULT FALSE,

                                replaced_by_token_id BIGINT,

                                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_refresh_tokens_user
                                    FOREIGN KEY (user_id) REFERENCES users(id),

                                CONSTRAINT fk_refresh_tokens_replacement
                                    FOREIGN KEY (replaced_by_token_id) REFERENCES refresh_tokens(id)
);


CREATE INDEX idx_refresh_tokens_user
    ON refresh_tokens(user_id);

CREATE INDEX idx_refresh_tokens_expiry
    ON refresh_tokens(expires_at);


-- ============================================================
-- 8. IDEMPOTENCY RECORDS
-- Prevent duplicate financial operations.
-- ============================================================

CREATE TABLE idempotency_records (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     user_id BIGINT NOT NULL,

                                     idempotency_key VARCHAR(128) NOT NULL,

                                     request_hash VARCHAR(255) NOT NULL,

                                     response_status INTEGER,

                                     response_body CLOB,

                                     transaction_id BIGINT,

                                     status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING',

                                     created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_idempotency_user
                                         FOREIGN KEY (user_id) REFERENCES users(id),

                                     CONSTRAINT fk_idempotency_transaction
                                         FOREIGN KEY (transaction_id) REFERENCES bank_transactions(id),

                                     CONSTRAINT uk_idempotency_user_key
                                         UNIQUE (user_id, idempotency_key),

                                     CONSTRAINT ck_idempotency_status
                                         CHECK (
                                             status IN (
                                                        'PROCESSING',
                                                        'COMPLETED',
                                                        'FAILED'
                                                 )
                                             )
);


CREATE INDEX idx_idempotency_transaction
    ON idempotency_records(transaction_id);


-- ============================================================
-- 9. AUDIT EVENTS
-- Security-sensitive and operational events.
-- ============================================================

CREATE TABLE audit_events (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              actor_user_id BIGINT,

                              event_type VARCHAR(100) NOT NULL,

                              entity_type VARCHAR(100),

                              entity_id VARCHAR(100),

                              ip_address VARCHAR(45),

                              user_agent VARCHAR(500),

                              details_json CLOB,

                              created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_audit_events_user
                                  FOREIGN KEY (actor_user_id) REFERENCES users(id)
);


CREATE INDEX idx_audit_events_actor
    ON audit_events(actor_user_id);

CREATE INDEX idx_audit_events_type
    ON audit_events(event_type);

CREATE INDEX idx_audit_events_created_at
    ON audit_events(created_at);



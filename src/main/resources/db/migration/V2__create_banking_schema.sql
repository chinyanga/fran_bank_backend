-- ============================================================
-- 3. LEDGER ACCOUNTS
-- Internal accounting accounts owned by the bank.
-- Customer bank accounts are linked to these ledger accounts.
-- ============================================================

CREATE TABLE ledger_accounts (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 account_code VARCHAR(50) NOT NULL UNIQUE,

                                 account_name VARCHAR(150) NOT NULL,

                                 account_type VARCHAR(30) NOT NULL,

                                 currency VARCHAR(3) NOT NULL,

                                 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                                 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT ck_ledger_account_type
                                     CHECK (
                                         account_type IN (
                                                          'ASSET',
                                                          'LIABILITY',
                                                          'EQUITY',
                                                          'REVENUE',
                                                          'EXPENSE'
                                             )
                                         ),

                                 CONSTRAINT ck_ledger_account_status
                                     CHECK (status IN ('ACTIVE', 'INACTIVE')),

                                 CONSTRAINT ck_ledger_account_currency
                                     CHECK (currency = UPPER(currency))
);


